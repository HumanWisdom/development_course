                      <h4 class="mtb0px blog_sub_title">
                        8. How much commitment do you bring to a relationship?
                        </h4>
                        <h4 class="mtb0px blog_desc">
                          Relationships can be hard work sometimes, and the temptation when the going gets tough is to
                          want to leave. It is always easier to end something than build something. We think the next
                          relationship will be easier, but it may not be, and you will encounter the same issues again.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          You will meet other people who are smarter and more attractive along the way — you may be
                          tempted to have an affair, or to leave this relationship and go with someone else. Desire is a
                          powerful force and your mind will convince you that its ‘okay’ and ‘no one will find out or get
                          hurt’.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          But they invariably do.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          That’s why commitment is important. Explore the <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/pathway/manage-your-emotions">Guided program on Desire</a>, to understand how
                          powerful this force is, and how to navigate it with intelligence.
                      </h4>
                      <h4 class="mtb0px blog_sub_title"> 9. Do you believe in changing others so you can feel more comfortable, or can you accept people as they are?
                        </h4>
                        <h4 class="mtb0px blog_desc">
                          Once you meet someone, there is an initial euphoric honeymoon phase which quickly transitions to
                          one of conflict where you try to change the other person to be more like you — if you are
                          vegetarian you want them to be one too, or the other way around, or you want people to share
                          your political or religious views, or your interests.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          This process goes on in the background and creates a lot of conflict.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Accepting people as they are and respecting their choices is a way of loving them. It’s not
                          easy, because it also means accepting other points of view as equally valid.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          That involves letting go of our attachment to our own points of view which we may have held dear
                          for so long that they have become part of our identity.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Explore the <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/relationships">Guided program on
                              Relationships</a> to explore this further.
                      </h4>
                      <h4 class="mtb0px blog_sub_title">
                            10. How easily can you say sorry?
                    </h4>
                    <h4 class="mtb0px blog_desc">
                         
                          It is surprising how few people know how to say sorry, easily and with meaning.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          It is a word that sticks in our throats sometimes. We struggle to admit we made a mistake and
                          were wrong. We can always find clever ways to justify our actions.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          But saying sorry is so important because it can heal other people’s hurts, diffuse
                          misunderstandings and bring people closer together. It is a skill we can all learn. It is a sign
                          of maturity and strength, not one of weakness.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Listen to this podcast on <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/audiopage/~podcasts~167.mp3/167/T/Saying%20sorry">The
                              importance of saying Sorry.</a>
                      </h4>
                      <h4 class="mtb0px blog_sub_title">
                            11. How self-aware are you? Are you committed to your own personal growth?
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          We usually look to relationships as a place to feel safe and to get our physical and emotional
                          needs met.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          But they are also an opportunity for learning about yourself and for personal growth.
                          Self-awareness can not only reduce conflict and deepen your relationships, but help you find
                          that sense of peace within yourself.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Explore the <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/wisdom-exercise">Self-awareness section of the app</a>
                          for more information.
                      </h4>
                      <h4 class="mtb0px blog_sub_title">
                            12. How well do you manage your own anger?
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Anger is part of being human and can protect us from harm, but also harm ourselves and others,
                          and damage our relationships.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          It is behind the 20% of relationships that experience domestic abuse.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Each time we get angry we assume it’s caused by the other person and lash out, withdraw, or give
                          the silent treatment. Each time this happens unchecked, the relationship suffers — and we damage
                          the one thing we need for our long-term happiness.
                      </h4>
                      <h4 class="mtb0px blog_desc">
                          Taking ownership of our own anger and managing it carefully can help us avoid this, and use
                          anger wisely.
                      </h4>
