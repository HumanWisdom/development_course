                <h4 class="mtb0px blog_sub_title">
                  Self-interest
                </h4>

                <h4 class="mtb0px blog_desc">
                  Our minds are wired to look after our own interests and those of the people or group we identify with as ours (my family, my company, my country), to the exclusion of others. We are wired to compete with each other, as individuals or countries and never question if this serves us. This is behind our relentless drive for self-expression, fame, recognition, power and money, and behind the failure of our relationships. This self-interest is not right or wrong, but is not understood or acknowledged and so operates in the background shaping our decisions. To address the challenge posed by AI we need to collaborate more and compete less, and think of the wider good, rather than our own narrow interests. We can only do this by waking up to our self interest operating in the background, pushing us to make choices that serve only us and justify those decisions to ourselves.
                </h4>

                <h4 class="mtb0px blog_desc">
                  When making any decision, our mind focuses just on whats good for us, or our organisation or country, but we need to also think of the impact on humanity as a whole, because each of us is part of it. We may make choices that benefit us in the short term, but in the long term may harm us all, and we need our inner intelligence to act with wisdom.
                </h4>

                <h4 class="mtb0px blog_sub_title">
                  Fear
                </h4>

                <h4 class="mtb0px blog_desc">
                  Fear is part of being human and can protect us from physical harm, but our imaginary fears can cause anxiety, and also shape our behaviour. It could for example make us develop AI as a force for destruction because we are worried others may do so. We did the same with the nuclear bomb. Or, if we are a company, develop it to maximise our profits and deter our competitors, afraid others will do so and undercut us.
                </h4>

                <h4 class="mtb0px blog_sub_title">
                  Our inner emptiness
                </h4>

                <h4 class="mtb0px blog_desc">
                  Within all of us is this feeling of emptiness, restlessness, or the void, which we find uncomfortable and want to escape from by being occupied or stimulated through entertainment. What happens when AI takes over our jobs and we no longer need to work? The agricultural revolution moved people en masse to the cities and the industrial revolution found new jobs for them. It is predicted AI will result in huge job losses. Without a sense of purpose and gainful occupation, our minds will seek stimulation through entertainment, or alcohol or drugs, or spiral into depression. We will need our inner intelligence to manage this change.
                </h4>

                <h4 class="mtb0px blog_desc">
                  This is not an argument to ban AI, but to educate ourselves to become more deeply intelligent so we can use it more wisely. This inner intelligence comes from shining a light into the back room of our thinking and the operating system we share. An understanding of the many hidden drivers in our own thinking like our conditioning, self-interest, inner emptiness and fear leads to wisdom. With this wisdom we can make better choices, keeping in mind our own needs and the needs of humanity as a whole. They are the same, because we will perish as a species without this wisdom. I recall the words of the legendary naturalist Sir David Attenborough who said ‘To continue we humans need wisdom’
                </h4>

