                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">I visited the 9/11 memorial in New York recently</span> and was moved by the beautiful water feature where the towers once stood and the wonderful museum with moving stories of bravery on the day. What also struck me was that many intelligence agencies had snippets of information that could have prevented the attacks, and if there was a spirit of collaboration they would have shared this information with each other, and the attacks could have been prevented. But each agency seemed to be in a competition for importance and influence and as a result intelligence sharing did not happen.
                </h4>

                <h4 class="mtb0px blog_desc">
                  This problem is also rife in organizations where <span class="blog_highlight_black">one department is at odds with another, and colleagues in the same department are sometimes at war with each other</span>. This contributes to low productivity, poor outcomes, and increased risk. It can also result in a loss of life. In the UK 10 million employees report workplace conflict. 900,00 workers took time off due to this (ACAS). In the US the cost of workplace conflict is estimated at $359 billion/year (CPP Inc., 2008). Companies with a poor corporate culture report a 48% turnover of staff, compared to 13% where there is a healthy one (Columbia University, 2012).
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">To address any problem, we need to explore the root cause, and in this case it lies in a deeper understanding of how the human mind is wired</span>. There are four hidden drivers in our thinking that contribute to the problem.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Conditioning">Conditioning</a><span class="blog_highlight_black">: We are all conditioned by our environment and past influences</span>. We are not aware of this, and yet become attached to our conditioning. This becomes our ‘normal’ and shapes our opinions and beliefs. Anyone we meet who is different is ‘wrong’ and we either avoid them or try and convince them of our point of view. Conflict follows.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Identity">Identity</a><span class="blog_highlight_black">: This is also an unconscious process.</span> If I belong to ‘Department A’ that becomes my identity, and I am at odds with ‘Department B’. We compete for influence and resources in the organization. We are part of the same organization but there is a turf war going on, which does not serve the larger whole.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Self%20Interest">Self-interest</a><span class="blog_highlight_black">: Our hidden self-interest operates in the background</span>, shaping our thoughts and actions. In any meeting I am always looking out for myself and resist anyone else gaining in influence, even though they may not be interfering in our work in any way. Our self-interest stops us living with integrity and collaborating with each other for the common good.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Comparison%20&amp;%20Envy">Comparison</a><span class="blog_highlight_black">: The unconscious process of comparison operates in the background</span> in all of us. If others are better in some way it generates a feeling of envy and resistance, and we blame others for how we are feeling. We often act then to pull the other person down and conflict follows.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">A deeper understanding of these hidden drivers in our thinking can help us put them to one side</span> and collaborate with others for the common good. It can also reduce interpersonal conflict. Each person needs to go on a journey of learning about themselves and this awakens wisdom, which can be life-changing in many ways.
                </h4>

                <h4 class="mtb0px blog_desc">
                  Organizations can help by <span class="blog_highlight_black">training staff in</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Awareness">self-awareness</a> — for their own personal growth. A natural by-product of this is better collaboration and reduced conflict. To be effective this training cannot be done as a one-off event because it is quickly forgotten. It also not effective imparted as pure information, though that is a good start. Regular group discussions combined with the use of the app and the built in online journal help users go on a journey of self-awareness, and it is this that brings transformation.
