                <h4 class="mtb0px blog_sub_title">
                 Implications of Poor Mental Health

                </h4>

                <h4 class="mtb0px blog_desc">
The repercussions of poor mental health extend beyond the individual. Depressed or anxious healthcare workers are more prone to making poor decisions and less likely to deliver high-quality care, which can affect patient outcomes. Burnout may also lead to higher turnover rates, creating staffing shortages that further stress remaining employees. Mental health issues lead to diminished job satisfaction, absenteeism, and a loss of productivity equivalent to billions of dollars annually. Toxic workplace cultures, where bullying or harassment is tolerated, worsen these outcomes.

                </h4>



                
