                <h4 class="mtb0px blog_desc">
                  By Dr Manoj Krishna, founder, HappierMe.
                </h4>

                <h4 class="mtb0px blog_desc">
                  The statistics around teen mental health should be a wake up call for all parents and educators. <span class="blog_highlight_black">According to the CDC 22% of teens think of suicide each year, 29% report a mental health problems and 40% are persistently sad. Smartphone addiction is around 37%</span> (NIH), and this has an adverse impact on mental health, communication skills and the ability to focus.
                </h4>

                <h4 class="mtb0px blog_desc">
                  Children who are emotionally distressed aren’t able to focus and learn to their potential. They are also likely to have behavioural challenges.
                </h4>

                <h4 class="mtb0px blog_desc blog_highlight_black">
                  Perhaps it is time to rethink the curriculum and add the teaching of these #10 vital life-skills to help children learn better and flourish in life.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#1.</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/breathing">Breathing exercises</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Simple breathing exercises can help us regulate our nervous system, creating a space before we react to events. It also allows us to calm ourselves down when we are emotionally distressed. Schools that teach this find children are able to focus better and are better behaved in class.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#2.</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/curated/manage-your-emotions">Understand and manage their emotions</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Our emotions, like anger, are powerful and children can struggle to cope with them. Helping them understand where they come from and how to regulate them can help them have healthier relationships and avoid conflict. For example, behind all anger is a feeling of being hurt, and if we can communicate that, rather than our anger, many situations can be diffused.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#3. Question their</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/conditioning">conditioning</a> <span class="blog_highlight_black">influences</span>
                </h4>

                <h4 class="mtb0px blog_desc">
                  We are all conditioned by our many influences, but are usually not aware we are being conditioned, and become attached to our various opinions and beliefs without questioning them. Understanding what is going on can help children navigate their digital world and not blindly accept what they come across without questioning it. It can also help them think critically and decide what is best for them.
                </h4>

                <h4 class="mtb0px blog_desc blog_highlight_black">
                  #4 Be comfortable being who they are
                </h4>

                <h4 class="mtb0px blog_desc">
                  Hidden from our own awareness, our mind is comparing all the time. Through <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/social-media">social media</a>, children can develop feelings of envy, feeling less than others, a pressure to conform so they can fit in, and this can result in a loss of confidence and a heartache that never goes away. By helping them understand what is going on, they can learn to compare themselves with others only when it serves them, and this can help them relax into being who they are.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#5 Learn to manage</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/stress">stress</a> <span class="blog_highlight_black">and</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/fear-anxiety">anxiety</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Up to 80% of teens feel stressed and 40% feel anxious. While these are normal human emotions, understanding what is behind them can help children manage them better. This can help with learning and behaviour, and help them cope with the many challenges they will face. For example, stress is often just the difference between how things are, and how we want them to be and acceptance can dissolve stress. Or, anxiety is often just our imagination playing up, exaggerating the possibility of bad things happening and seeing this clearly can help children to manage it better.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#6 Avoid and overcome</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/habit-addiction">addiction</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Our minds are restless and we are always looking for something out there to make us feel good ‘in here’. The smartphone is an easy escape from that feeling. The problem is that the more our minds are stimulated, the more stimulation we need and this can easily lead to addiction — to social media, drink, vaping, gambling and so on. Helping them understand what is going on in their own mind can help them make more intelligent choices.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#7 Have healthy</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/relationships">relationships</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Learning how to have healthy relationships, with depth, meaning, and less conflict is perhaps the most important skill we can teach children. Their long term happiness depends on it. It is a skill that everyone can learn. The more we understand ourselves, the easier it is to understand others. For example, understanding our emotional needs, our expectations, our prejudices and our need to change people to be more like us, can help us have healthier relationships.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#8</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/communication">Communicate with care</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Learning to communicate effectively can help children build happier relationships and also contribute to their success in life. This may include learning to listen with curiosity and without judgement, pausing before speaking and asking how it is going to be received, and trying to understand what the person may not be saying.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#9 Learn to</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/kindness">be more kind</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Kindness is the glue that holds relationships together, and a culture of kindness can transform homes and workplaces so we can thrive in them, but it does not come easily to most. The first step is to realise the importance of being kind to ourselves and to others, and then find out what gets in the way of being more kind. It could be our self-interest for example.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">#10</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/teenagers/criticism">Deal with criticism</a>
                </h4>

                <h4 class="mtb0px blog_desc">
                  Learning how to deal with criticism in a more positive way is important for our own mental health, but also a valuable skill at work. Understanding that criticism is an opportunity for reflection and personal growth may allow us to be grateful for it and ignore it if we think it is unjustified. Offering criticism with care is an equally important skill which can help avoid straining relationships and creating conflict.
                </h4>

