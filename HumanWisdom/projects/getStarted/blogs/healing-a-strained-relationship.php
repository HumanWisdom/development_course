                <h4 class="mtb0px blog_desc">
                  <a class="blog_highlight_peach td_underline" href="https://humanwisdom.me/adults/three-steps-enquiry/s37000" target="_blank">To heal ourselves, there is a simple 3-step process of enquiry we can all follow.</a> The first step is to be aware of what we are feeling, for example we may be feeling hurt, or envious. The second step is to take ownership of how we are feeling and accept that the feeling comes from within us, without blaming ourselves or others. This is not easy. The last step is to ask a simple question — <span class="blog_highlight_black">What is going on in our mind to make us feel this way?</span> Doing the work of looking and learning about ourselves translates what we may have read, for example in this article, into a living reality in ourselves. This is like <span class="blog_highlight_black">switching a light on in our own mind</span>, and with this understanding we can see that deep down we are all the same human being — others also act from their conditioning, self-interest, and feeling of being hurt — as we do. Their mind is also comparing, and they are not aware of it. They have expectations they are not aware of which they expect others to meet — just as we do. This understanding brings compassion because we see others are not aware of what is going on in the deeper layers of their own thinking, and that leads to compassion. With compassion we can forgive ourselves and others, and this can heal the most intractable problems in relationships. This wisdom can prevent these problems from occurring in the first place. This leads to peace.
                </h4>

                <h4 class="mtb0px blog_desc">
