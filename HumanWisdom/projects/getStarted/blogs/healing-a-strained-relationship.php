                <h4 class="mtb0px blog_desc">
                  Dear Harry and William,
                </h4>

                <h4 class="mtb0px blog_desc">
                  Like all siblings who fall out, you must both be hurting and your father perhaps even more so, to see his sons unhappy and not on talking terms. This letter is for you, but also for people everywhere whose <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Relationships">relationships</a> sour and end up in conflict. Your suffering is not unique — the same patterns are repeated everywhere.
                </h4>

                <h4 class="mtb0px blog_desc">
                  How can wisdom, which comes from a deeper self-understanding, help you to heal your relationship, and perhaps even more importantly, stop relationships breaking down in the first place?
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">Our mind assumes that others are responsible for the hurt we feel</span>, but if we look carefully, our pain comes from <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Reactive%20Mind">how our mind reacts to situations</a>, because another person may react very differently and not be hurt in the same way. Join me as we go on a journey to understand why our mind automatically reacts in the way that it does, and how that deeper understanding can bring illumination, freedom, compassion, and peace.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">All of us are</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Conditioning">conditioned</a> <span class="blog_highlight_black">by our many experiences</span> and influences which are stored in our memory and become the ‘me’, including our old traumas. We are not aware we are conditioned and yet become attached to our conditioning. All our opinions, beliefs and narratives of how we see the world come from this pool of conditioning, which is ever changing as we gather new experiences. We assume we are right, and those who see things differently are wrong. We try to convince others of our point of view and if they do not agree, we can withdraw or get upset. Conflict follows.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">Unknown to us,</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Comparison%20&amp;%20Envy">our minds compare</a> <span class="blog_highlight_black">all the time</span> — it’s an essential function and how we make sense of the world. But it can also cause envy and feelings of being less than, and we can blame the hurt we feel on how others are behaving, even if they had no intention of hurting us. We do not see that our hurt is caused by the hidden process of comparison in our own thinking. It does not help that others may compare us to our siblings, and this reinforces our narrative.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">We all have</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Emotional%20Needs">emotional needs</a> <span class="blog_highlight_black">we expect others to meet</span> and when these needs are not met, we can get hurt and blame them for how we feel. This may be for love, or recognition, or to feel important, or to be listened to and understood. The closer our relationship the greater our expectations of others. We are not aware that these expectations come from our own thinking process and always regard them as reasonable. These needs are not wrong, but we are usually not aware of them. It is not easy to accept that our feeling of being hurt comes from our own unmet expectations.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">We rarely</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Communication">communicate</a> <span class="blog_highlight_black">with wisdom</span>. We often do not listen deeply enough to what is not being said or pause before speaking to ask how it is going to be received. When we are criticised, our hurt and anger can make us lash out, saying things we may not mean and without a regard to the consequences.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">When any</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Relationships">relationship</a> <span class="blog_highlight_black">breaks down, we blame each other</span> and are able to cite situations where the other person behaved badly. We recruit others to agree with us, to justify our narrative of what happened. We have an urge to be right and believe we have been wronged. If we zoom out of the situation and look at the entire timeline of the relationship, we can see it is just a series of and reactions in a domino fashion. Each person picks the episodes in the timeline that justify their narrative, overlooking their own role in the breakdown of the relationship. This is not unique to you. We all do it.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">One more factor that plays out in the background is our inherent</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Self%20Interest">self-interest</a>. It is wired into the way our mind functions. We are usually not aware of it and don’t want to admit it because we don’t want to feel we are selfish. If we look carefully though, it plays a role in most of the decisions we make, including in our relationships.
                </h4>

