                <h4 class="mtb0px blog_desc">
                  How can we apply this deeper understanding of ourselves to have healthy relationships, prevent problems, and heal the cracks that appear?
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">Begin gently. Let your</span> <a class="blog_highlight_peach td_underline" href="https://happierme.app/adults/site-search/Anger">anger</a> <span class="blog_highlight_black">go for starters.</span> Realise you are brothers, and deep down are the same human being. Your anger harms you and the people you love, and no one in the family can be happy as a result.
                </h4>

                <h4 class="mtb0px blog_desc">
                  <span class="blog_highlight_black">The key to healing is to understand the hurt each person feels</span>. Sometimes we can heal our own hurt through a journey of forgiveness and by connecting with our own wisdom. We may realise that the real reason for our hurt lay in us — in our unmet expectations for example. The other way is to try and heal the other persons hurt. We can do this by listening deeply to their story without interrupting or being defensive, making a real effort to understand things from their perspective. Then we can say sorry. This is not about accepting blame, or blaming others, but stepping away from that field of blame, and realising it does not serve the healing process.
                </h4>

