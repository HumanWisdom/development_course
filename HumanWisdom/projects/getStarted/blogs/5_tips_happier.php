                </h4>

                <h4 class="mtb0px blog_sub_title">
                2. Realise That Happiness Is an Inside Job
                </h4>

                <h4 class="mtb0px blog_desc">
                Our mind is wired to look "out there" for things to make us feel good "in here." If we don't get what we want, we become unhappy. If we do get it, we become anxious about losing it — and suffer when we eventually do. Chasing happiness out in the world can quietly lead to suffering inside.
                </h4>

                <h4 class="mtb0px blog_desc">
                Each thought has the power to make us happy or unhappy, and it's a revelation to realise that we can choose what we think. We can choose how we look at people or situations — generously, or with the glass "half empty." We can choose our actions too, becoming aware of old habits that don't serve us — being on the phone constantly, or eating more than our body needs — and starting to change them.
                </h4>

                <h4 class="mtb0px blog_desc">
                We can reframe a negative thought about someone with a more positive one (we rarely know someone's full story, or what they're going through that day). Or we can focus on what we have, and be grateful, rather than on what we lack.
                </h4>

