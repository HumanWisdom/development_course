                <h4 class="mtb0px blog_sub_title">
                1. Find Out What Happiness Means to You
                </h4>

                <h4 class="mtb0px blog_desc">
                Happiness means different things to different people.
                </h4>

                <h4 class="mtb0px blog_desc">
                <b>Is happiness pleasure?</b> The short-lived burst you get from a meal out, some praise, or achieving something? Each time it ends, we're left feeling a little empty, chasing the next source of pleasure. Over time, this constant stimulation dulls the mind, making it less sensitive to people and to the beauty of the world.
                </h4>

                <h4 class="mtb0px blog_desc">
                <b>Is happiness the absence of unhappiness?</b> Some people feel happy simply because they aren't unhappy. Life ticks over day to day, focused on what needs doing. The routine feels safe, but inside we can feel bored and lose the joy of living.
                </h4>

                <h4 class="mtb0px blog_desc">
                <b>Or is happiness peace?</b> A deep sense of contentment that comes from connecting with your own silence, wanting nothing more? A mind at peace tends to be more sensitive — to what your body needs, to your own moods, to others and what they may not be saying, and to the beauty of the world.
                </h4>

