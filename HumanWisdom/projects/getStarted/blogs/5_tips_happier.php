                </h4>

                <h4 class="mtb0px blog_sub_title">
                4. Make Kindness Your First Instinct
                </h4>

                <h4 class="mtb0px blog_desc">
                We often assume kindness is something we do for others, as a favour to them — not realising it contributes to our own happiness too. That's because kindness is the glue that holds our relationships together, and those relationships are the foundation of our own happiness — nourishing us daily, and sheltering us from life's storms.
                </h4>

                <h4 class="mtb0px blog_desc">
                Being kind can be as simple as offering someone a smile, a hug, or making the morning cup of tea. It takes conscious effort, because by default our mind tends to be preoccupied with itself — and to be kind, we need a mind that's at peace with itself; a mind in turmoil is even more caught up in its own suffering.
                </h4>

