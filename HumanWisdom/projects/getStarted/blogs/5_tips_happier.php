                <h4 class="mtb0px blog_sub_title">
                3. Be Curious, Keep Learning About Yourself
                </h4>

                <h4 class="mtb0px blog_desc">
                Our mind responds in predictable ways, and if we want the New Year to bring real renewal, we need to be curious about what we think and feel — and why.
                </h4>

                <h4 class="mtb0px blog_desc">
                These are useful questions that lead to fresh discoveries about ourselves: "What's going on in my mind to make me feel this way? Or behave this way? Or think this way?" Questions like these open the door to learning about the hidden patterns that drive our thoughts, feelings and actions.
                </h4>

                <h4 class="mtb0px blog_desc">
                For example, realising that every opinion we hold so strongly is a product of our conditioning — influences we may not even be aware of. Understanding this lets us explore how our conditioning shapes our life, and let go of opinions, beliefs and prejudices that no longer serve us. It helps us understand other perspectives better, and feel closer to others rather than clinging to old stories and beliefs. Throughout, it matters that we can look at ourselves without judgement — without justifying what we see as right, or criticising ourselves for being "wrong."
                </h4>

