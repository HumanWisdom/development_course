                5. Be Sensitive to Beauty
                </h4>

                <h4 class="mtb0px blog_desc">
                As we go through life, our minds can grow more and more dull — focused on accumulation and achievement, driven by a hidden fear of not having enough, or a desire to be someone "important." Chasing success, pleasure or praise (and even getting it), we can be oblivious to what we're losing along the way — our sensitivity.
                </h4>

                <h4 class="mtb0px blog_desc">
                In our preoccupation, we can become insensitive to the beauty of the world — the light in the trees, the touch of the breeze, clouds moving across the sky, or the detail of a flower if you really look at it. Life offers so many joys every day, but we need to open our heart to receive them.
                </h4>

                <h4 class="mtb0px blog_desc">
