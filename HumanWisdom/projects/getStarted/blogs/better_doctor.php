                <h4 class="mtb0px blog_sub_title">
                    1. Manage your own mental health
                </h4>

                <h4 class="mtb0px blog_desc">
                    <span class="blog_highlight_black">
                        Stress and anxiety are automatic reactions from our thinking to external triggers.
                    </span>
                    This is not easy to see because our mind assumes external events are responsible for how we feel. Though the trigger is on the outside, the reaction is on the inside. We may not be able to change the trigger, but we can be in control of our reactions, and self-knowledge helps us to do this. We begin with exercises to calm our mind so there is a pause between the trigger and the reaction, and then explore where our reactions come from. This understanding can put us in charge of how we feel, and can empower us to respond to our challenges with a mind that is calm.
                </h4>

