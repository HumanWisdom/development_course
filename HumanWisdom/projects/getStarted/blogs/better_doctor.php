                </h4>

                <!-- 5 -->
                <h4 class="mtb0px blog_sub_title">
                    5. Be happier
                </h4>

                <h4 class="mtb0px blog_desc">
                    <span class="blog_highlight_black">
                        We all want to be happy and often assume our happiness comes from the outside,
                    </span>
                    through all our activities in the world, and that we will be happy if we get what we want. Doctors are no exception. If we don't get what we want, we can become unhappy.
                </h4>

                <h4 class="mtb0px blog_desc">
                    Happy doctors are more productive and boost everyone's morale. Unhappy ones do the opposite.
                </h4>

                <h4 class="mtb0px blog_desc">
                    Our happiness depends on many factors: our mental health, our relationships, our work, our mindset, any addictions we may have and how we manage our emotions. If we are unhappy in any one of these areas, our happiness takes a hit and we can become frustrated, and this can impact our decision making, our mental health and our performance.
                </h4>

                <h4 class="mtb0px blog_desc">
                    <span class="blog_highlight_black">
                        Self-knowledge can help us understand that happiness is an inside job,
                    </span>
                    and we can be in charge of our own happiness by understanding what gets in the way of being happy, developing a positive mindset, managing our expectations, being content with who we are, and developing a calm mind.
                </h4>

