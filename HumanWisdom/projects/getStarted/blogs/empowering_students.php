                <h4 class="mtb0px blog_desc">
                  <strong>To address any problem we need to understand and address the root cause, rather than just the symptoms</strong>. In any situation there is an external trigger and an automatic internal reaction which creates a feeling of emotional distress. Often, we cannot change the external trigger, but can, with some guidance, change how we respond. It is not the traffic jam, for example, but the way our mind reacts to it that creates the feeling of stress. Once we can separate the trigger and our response, we can be curious and explore why our mind reacts in the way that it does, and if there are different ways to respond. The more we learn about ourselves, the more we can be in charge of how we think, feel and act. This is simple once we know how, and it is one of many ways we can feel empowered to avoid and overcome mental health problems more easily. Everyone can learn how to do this, just like everyone can learn how to swim. Once you learn to swim, you never forget.
                </h4>

